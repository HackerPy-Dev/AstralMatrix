function renderCitySuggestions() {
  var box = document.getElementById('city-sug');
  box.innerHTML = '';
  _filtered.forEach(function(city, i) {
    var div = document.createElement('div');
    div.className = 'city-opt' + (i === _hlIdx ? ' hl' : '');
    div.innerHTML = '<div class="city-opt-name">' + city.n + '</div>'
      + '<div class="city-opt-meta">' + city.c + ' · ' + city.lat.toFixed(2) + '°, ' + city.lon.toFixed(2) + '°</div>';
    (function(c) {
      div.addEventListener('mousedown', function() { selectCity(c); });
    })(city);
    box.appendChild(div);
  });
  box.style.display = 'block';
}

